numero = int(input("Digite um número (0 a 6): "))

if numero == 0:
    print("Domingo")
elif numero == 1:
    print("Segunda-feira")
elif numero == 2:
    print("Terça-feira")
elif numero == 3:
    print("Quarta-feira")
elif numero == 4:
    print("Quinta-feira")
elif numero == 5:
    print("Sexta-feira")
else:
    print("Sábado")
